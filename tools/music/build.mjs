// Generates js/music_data.js (the game's single-file soundtrack payload) from the rendered files in assets/music/.
// usage: node tools/music/build.mjs [--opus-only]
//
// Full pipeline (from the project root):
//   node tools/music/fetch_samples.mjs --download   # ~1.2 GB of CC0 VSCO 2 CE samples -> tools/music/downloads/
//   node tools/music/analyze.mjs                    # onset / loudness / tuning analysis -> tools/music/out/analysis.json
//   node --max-old-space-size=8192 tools/music/render.mjs [--qa]   # score -> master WAV -> assets/music/*.opus|mp3|json
//   node tools/music/build.mjs                      # -> js/music_data.js
// The composition itself is tools/music/score.mjs.
// Input:  assets/music/wingnut_theme.opus (Ogg Opus, primary), .mp3 (fallback for browsers that cannot decode Opus,
//         e.g. older Safari), .json (title / bpm / loop points written by render.mjs)
// Output: js/music_data.js -> export const MUSIC = { title, bpm, loopStart, loopEnd, duration, opus, mp3? }
// Also: js/music_tracks.js, the manifest of the other tracks (TRACK_FILES below; rendered by render_mainspring.mjs and
// render_night.mjs through encode_track.mjs). They are not embedded: js/music.js fetches a track's file when a mission
// first needs it, so the page's first load does not grow. tools/build.mjs copies the files next to the built page.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
const DIR = join(ROOT, 'assets', 'music');
const NAME = 'wingnut_theme';
const BUDGET = 3.5e6; // bytes of encoded audio we are willing to ship inside the page

const meta = JSON.parse(readFileSync(join(DIR, `${NAME}.json`), 'utf8'));
const opus = readFileSync(join(DIR, `${NAME}.opus`));
let mp3 = !process.argv.includes('--opus-only') && existsSync(join(DIR, `${NAME}.mp3`)) ? readFileSync(join(DIR, `${NAME}.mp3`)) : null;
if (opus.subarray(0, 4).toString('latin1') !== 'OggS') throw new Error('opus file is not an Ogg stream');
if (mp3 && opus.length + mp3.length > BUDGET) { console.log(`mp3 fallback dropped: ${(opus.length + mp3.length) / 1e6} MB exceeds budget`); mp3 = null; }
const num = (x) => Math.round(x * 1e6) / 1e6;
const fields = {
  title: meta.title, bpm: meta.bpm, loopStart: num(meta.loopStart), loopEnd: num(meta.loopEnd), duration: num(meta.duration),
};
const lines = [
  '// js/music_data.js — GENERATED by tools/music/build.mjs from assets/music/ — do not edit by hand.',
  `// "${meta.title}" — original orchestral score for PROJECT WINGNUT (composed as code in tools/music/score.mjs).`,
  '// Rendered offline from VSCO 2 Community Edition samples (CC0, Versilian Studios / Sam Gossner — credit appreciated).',
  `// Payload: Ogg Opus ${(opus.length / 1024).toFixed(0)} KiB${mp3 ? ` + MP3 fallback ${(mp3.length / 1024).toFixed(0)} KiB` : ''}, base64. Loop: [loopStart, loopEnd) seconds; the`,
  '// intro before loopStart plays once. Audio after loopEnd is a copy of the loop head (decoder-offset safety margin).',
  'export const MUSIC = {',
  ...Object.entries(fields).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`),
  `  opus: '${opus.toString('base64')}',`,
  ...(mp3 ? [`  mp3: '${mp3.toString('base64')}',`] : []),
  '};',
  'export default MUSIC;',
  '',
];
const out = join(ROOT, 'js', 'music_data.js');
writeFileSync(out, lines.join('\n'));
const size = Buffer.byteLength(lines.join('\n'));
console.log(`wrote ${out}: ${(size / 1e6).toFixed(2)} MB (opus ${(opus.length / 1e6).toFixed(3)} MB${mp3 ? `, mp3 ${(mp3.length / 1e6).toFixed(3)} MB` : ''}; audio total ${((opus.length + (mp3 ? mp3.length : 0)) / 1e6).toFixed(3)} MB)`);
console.log(`loop ${fields.loopStart}..${fields.loopEnd} s of ${fields.duration} s @ ${fields.bpm} BPM — "${fields.title}"`);

// ---- streamed tracks (js/music_tracks.js) ---------------------------------------------------------------------------
const TRACK_FILES = { epic: 'epic', mainspring: 'mainspring', night: 'night' };   // track name -> assets/music/<file>.opus|mp3|json
const tracks = {};
for (const [track, file] of Object.entries(TRACK_FILES)) {
  const tm = JSON.parse(readFileSync(join(DIR, `${file}.json`), 'utf8'));
  const head = readFileSync(join(DIR, `${file}.opus`)).subarray(0, 4).toString('latin1');
  if (head !== 'OggS') throw new Error(`${file}.opus is not an Ogg stream`);
  tracks[track] = { title: tm.title, bpm: tm.bpm, loopStart: num(tm.loopStart), loopEnd: num(tm.loopEnd), duration: num(tm.duration),
    opusUrl: `assets/music/${file}.opus`, mp3Url: `assets/music/${file}.mp3` };
}
const tl = [
  '// js/music_tracks.js — GENERATED by tools/music/build.mjs from assets/music/*.json — do not edit by hand.',
  '// Soundtrack tracks streamed on demand (js/music.js): URLs relative to the page, loop [loopStart, loopEnd) seconds.',
  '// "Ceiling Unlimited" is embedded instead (js/music_data.js).',
  `export const MUSIC_TRACKS = ${JSON.stringify(tracks, null, 2)};`,
  '',
];
writeFileSync(join(ROOT, 'js', 'music_tracks.js'), tl.join('\n'));
console.log(`wrote js/music_tracks.js: ${Object.entries(tracks).map(([k, t]) => `${k} "${t.title}" loop ${t.loopStart}..${t.loopEnd}`).join(', ')}`);
